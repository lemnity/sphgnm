/**
 * Детерминированный генератор псевдослучайных чисел.
 *
 * ПОЧЕМУ НЕ Math.random(). Лендинг собирается в статику (next build → out/):
 * разметка стены рендерится на сборке, а потом гидрируется в браузере. Math.random()
 * дал бы на сервере одну стену, в браузере — другую, React увидел бы расхождение
 * атрибутов d/transform у сотни узлов и переразметил бы всё поддерево. В консоли
 * это hydration mismatch, на экране — моргание стены при загрузке.
 *
 * Seed фиксирован в config.WALL_SEED, поэтому стена всегда одна и та же —
 * и на сервере, и в браузере, и между сборками. Меняешь seed — получаешь
 * другую композицию, и это единственный способ её перегенерировать.
 *
 * Алгоритм — mulberry32: 32-битный счётчик со смешиванием. Взят не за качество
 * статистики (для декоративной раскладки её хватит с запасом), а за то, что он
 * помещается в пять строк и не тянет зависимость.
 */

/** Функция-источник: каждый вызов возвращает следующее число в [0, 1). */
export type Rng = () => number;

/**
 * Создаёт независимый поток случайных чисел.
 *
 * Каждая подсистема (раскладка растений, форма листа, блики, ambient) берёт
 * СВОЙ поток от своего seed. Иначе добавление одного блика сдвигало бы всю
 * последовательность и перетасовывало стену целиком — отлаживать такое нельзя.
 */
export function createRng(seed: number): Rng {
  // >>> 0 приводит к беззнаковому 32-битному: без него отрицательный seed
  // уводит арифметику в другую ветку и ломает воспроизводимость.
  let a = seed >>> 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Равномерное число в [min, max). */
export function range(rng: Rng, min: number, max: number): number {
  return min + rng() * (max - min);
}

/** То же, но границы приходят парой — так они и хранятся в config. */
export function rangeOf(rng: Rng, pair: readonly [number, number]): number {
  return range(rng, pair[0], pair[1]);
}

/** Целое в [min, max]. */
export function intRange(rng: Rng, min: number, max: number): number {
  return Math.floor(range(rng, min, max + 1));
}

/**
 * Значение, смещённое к центру диапазона.
 *
 * Сумма трёх равномерных величин даёт колоколообразное распределение (частный
 * случай ЦПТ). Нужно там, где равномерность выглядит неестественно: размеры
 * растений, длины листьев. При равномерном распределении в стене одинаково
 * часто встречаются гиганты и карлики, и она читается как случайный мусор;
 * с колоколом большинство растений средние, а крайности редки — как в природе.
 */
export function bell(rng: Rng, min: number, max: number): number {
  const t = (rng() + rng() + rng()) / 3;
  return min + t * (max - min);
}

/** Случайный знак: −1 или +1. */
export function sign(rng: Rng): number {
  return rng() < 0.5 ? -1 : 1;
}

/** Случайный элемент массива. */
export function pick<T>(rng: Rng, items: readonly T[]): T {
  return items[Math.floor(rng() * items.length)] as T;
}

/**
 * Округление до N знаков.
 *
 * Нужно не для красоты, а для веса статики: SVG-path с координатами вида
 * 12.834729384729 занимает вчетверо больше байт, чем 12.83, а разницы в
 * пикселях нет — путь всё равно ляжет в растр. На стене из ~40 розеток по
 * 7 листьев это сотни килобайт разметки.
 */
export function round(value: number, digits = 2): number {
  const k = 10 ** digits;
  return Math.round(value * k) / k;
}
