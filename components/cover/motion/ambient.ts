/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  AMBIENT — БЕСКОНЕЧНАЯ ЖИЗНЬ СТЕНЫ (ТЗ п.4 и п.8)
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Когда хореография прокрутки отработала, стена не должна замирать: неподвижная
 * зелень мгновенно читается фотографией. Здесь живёт то, что делает её живой —
 * покачивание, дыхание, микродрейф и медленный свет.
 *
 * ── ГЛАВНОЕ РЕШЕНИЕ: ЧЕТЫРЕ НЕЗАВИСИМЫХ КОЛЕБАНИЯ, А НЕ ОДИН ТАЙМЛАЙН ──
 *
 * Соблазн — собрать покачивание, масштаб и дрейф в один timeline на растение.
 * Так делать нельзя: у общего таймлайна один период, и все четыре свойства
 * возвращаются в исходную точку ОДНОВРЕМЕННО. Глаз ловит этот момент как удар
 * метронома, и стена начинает читаться заводной игрушкой.
 *
 * Поэтому на каждое растение — четыре отдельных твина с разными периодами
 * (3.4…9.5 с) и разными стартовыми фазами. Суммарная траектория замыкается
 * только на общем кратном всех четырёх периодов, то есть практически никогда:
 * движение выглядит непериодическим, хотя каждая его составляющая — синус.
 * Это фигура Лиссажу, и именно она даёт ощущение живого, а не анимированного.
 *
 * GSAP разрешает конфликты твинов ПОСВОЙСТВЕННО, поэтому четыре твина на один
 * элемент (rotation / scale / x / y) не перебивают друг друга — они пишут в
 * разные каналы общей матрицы трансформации.
 *
 * ── ПРОИЗВОДИТЕЛЬНОСТЬ ──
 *
 * 1. Анимируются ТОЛЬКО transform-свойства. Ни одного layout-свойства, ни
 *    одной перерисовки: работа целиком уходит на композитор.
 * 2. Ambient умеет ставиться на паузу и делает это в двух случаях —
 *    пока стена размыта на входе/выходе (blur по движущемуся содержимому
 *    заставляет браузер пересобирать растр каждый кадр) и когда обложка
 *    вообще ушла из вьюпорта. Считать синусы для того, чего не видно, незачем.
 */

import { gsap } from "gsap";

import { EASE, LIGHT } from "./config";
import { LIVE_LAYERS } from "./leaves";
import type { Glint, Oscillation, Plant } from "./types";

/** Управление ambient-слоем снаружи: пауза на время размытия, снятие при уходе. */
export interface AmbientHandle {
  play: () => void;
  pause: () => void;
  destroy: () => void;
}

/**
 * Общая фабрика колебания.
 *
 * Твин строится через fromTo вокруг нуля (−amount/2 … +amount/2), а не через
 * to от текущего значения: to(0 → amount) качал бы растение только в одну
 * сторону от исходного положения, и вся стена оказалась бы смещена.
 *
 * `totalTime(phase)` перематывает твин в момент `phase` сразу после создания.
 * Это и есть расстройка фаз: без неё все растения стартуют из одной точки
 * синуса и первые секунды стена дышит хором — самый заметный признак
 * «анимации по классу».
 */
function oscillate(
  target: Element,
  prop: "rotation" | "scale" | "x" | "y",
  osc: Oscillation,
  opts: { center?: number; unit?: number } = {},
): gsap.core.Tween {
  const center = opts.center ?? 0;
  const half = osc.amount / 2;

  const tween = gsap.fromTo(
    target,
    { [prop]: center - half },
    {
      [prop]: center + half,
      duration: osc.duration,
      ease: EASE.breathe, // sine.inOut — единственная кривая без рывка на развороте
      repeat: -1,
      yoyo: true,
      // Матрицу считаем в 3D: браузер выносит элемент на свой слой композитора
      // и больше не трогает его при перерисовке соседей.
      force3D: true,
      // Смысла ставить will-change нет: force3D уже промотировал слой, а лишний
      // will-change на 38 растениях — это 38 постоянно удерживаемых текстур.
      overwrite: false,
    },
  );

  tween.totalTime(osc.phase);
  return tween;
}

/**
 * Заводит жизнь во всех растениях стены.
 *
 * `scope` — корневой узел обложки; поиск идёт по нему, а не по document,
 * чтобы две обложки на одной странице не перехватывали узлы друг у друга.
 */
export function createAmbient(scope: HTMLElement, plants: Plant[], glints: Glint[]): AmbientHandle {
  const tweens: gsap.core.Tween[] = [];

  for (const plant of plants) {
    // Дальний план не оживляем: он размыт, и любое шевеление внутри заставляет
    // браузер пересчитывать размытие всего слоя каждый кадр. Подробный разбор —
    // у LIVE_LAYERS в leaves.ts. Замер: 12 → 22 fps только на этом.
    if (!LIVE_LAYERS.has(plant.layer)) continue;

    // Отдельный узел под ambient — НЕ тот, что двигает scroll-хореография.
    // Причина: reveal анимирует y/scale/opacity того же растения, и на общем
    // узле GSAP при первом же scrub-кадре снял бы ambient-твины как конфликтующие.
    // Разделение по узлам разводит их по разным матрицам и снимает конфликт вовсе.
    const node = scope.querySelector<HTMLElement>(`[data-ambient="${plant.id}"]`);
    if (!node) continue;

    const a = plant.ambient;

    // 1. Покачивание листьев. transformOrigin вынесен НИЖЕ центра розетки
    //    (см. CSS .cover-plant__ambient): куст качается от основания, как на
    //    стебле. Вращение вокруг центра выглядит как крутящаяся снежинка.
    tweens.push(oscillate(node, "rotation", a.sway));

    // 2. Дыхание. Один твин на общий `scale`, а не пара scaleX/scaleY: у пары
    //    тот же период и та же фаза, то есть она заведомо делала одно и то же
    //    двумя твинами. На 78 живых подушках это была лишняя сотня твинов на
    //    тикере GSAP. Разводить оси по разным периодам НЕЛЬЗЯ — подушка начнёт
    //    плющиться, и это уже не дыхание, а желе.
    tweens.push(oscillate(node, "scale", a.breathe, { center: 1 }));

    // 3–4. Микродрейф по осям. Разные периоды у X и Y — вместе они рисуют
    //      медленную петлю вместо диагональной черты.
    tweens.push(oscillate(node, "x", a.driftX));
    tweens.push(oscillate(node, "y", a.driftY));
  }

  // ── Солнечные блики (ТЗ п.8) ──
  // Тот же принцип: дрейф и «дыхание» яркости — независимые колебания с очень
  // длинными периодами (18–30 с). Медленность здесь принципиальна: свет,
  // который движется заметно, читается анимированной картинкой; свет на грани
  // восприятия — живым освещением.
  for (const glint of glints) {
    const node = scope.querySelector<HTMLElement>(`[data-glint="${glint.id}"]`);
    if (!node) continue;

    tweens.push(oscillate(node, "x", glint.drift));
    // Вертикальный дрейф чуть медленнее горизонтального — солнце ходит по
    // дуге, а не по прямой.
    tweens.push(
      oscillate(node, "y", { ...glint.drift, duration: glint.drift.duration * 1.37, phase: glint.drift.phase * 0.6 }),
    );

    // Яркость — единственное здесь НЕ transform-свойство. Допустимо: opacity
    // тоже композитится, перерисовки не вызывает, а элементов всего четыре.
    tweens.push(
      gsap.fromTo(
        node,
        { opacity: LIGHT.glowOpacity[0] },
        {
          opacity: LIGHT.glowOpacity[1],
          duration: glint.glow.duration,
          ease: EASE.breathe,
          repeat: -1,
          yoyo: true,
          overwrite: false,
        },
      ),
    );
    (tweens[tweens.length - 1] as gsap.core.Tween).totalTime(glint.glow.phase);
  }

  let running = true;

  return {
    play() {
      if (running) return;
      running = true;
      // resume(), а не play(): play() сбрасывает голову твина в начало, и вся
      // стена дёрнулась бы в исходную фазу при каждом снятии паузы.
      for (const t of tweens) t.resume();
    },
    pause() {
      if (!running) return;
      running = false;
      for (const t of tweens) t.pause();
    },
    destroy() {
      // kill() снимает твин с тикера GSAP и отпускает ссылку на узел. Без него
      // после размонтирования компонента тикер продолжает крутить сотню твинов
      // по элементам, которых уже нет в документе.
      for (const t of tweens) t.kill();
      tweens.length = 0;
    },
  };
}
