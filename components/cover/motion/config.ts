/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  КОНФИГУРАЦИЯ ОБЛОЖКИ «ЖИВАЯ СТЕНА»
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Единственное место, где живут числа. Ни один другой модуль системы не имеет
 * права держать у себя магическую константу длительности, easing или амплитуды:
 * если значение понадобилось в двух местах — оно переезжает сюда.
 *
 * Почему так строго. Хореография из девяти актов (проявление → рост → листья →
 * ambient → parallax → текст → счётчики → свет → уход) настраивается не по
 * одному числу, а по их СООТНОШЕНИЮ: сдвинешь длительность роста — поедет
 * стагger листьев, за ним текст, за ним счётчики. Когда числа разбросаны по
 * пяти файлам, такая правка превращается в археологию.
 *
 * Все длительности — в секундах (единица GSAP). Все расстояния — в пикселях,
 * если явно не сказано иное.
 */

