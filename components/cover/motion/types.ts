/**
 * Общие типы системы анимации обложки.
 *
 * Вынесены отдельным модулем, чтобы geometry (чистая математика, работает и на
 * сервере) не тянул за собой gsap, а модули движения не тянули генератор форм.
 * Импорт типов стирается при сборке, поэтому такой файл ничего не весит.
 */

/** Точка/вектор. */
export interface Vec2 {
  x: number;
  y: number;
}

/**
 * Слой глубины стены. Их три, и это не украшение, а основа объёма:
 * parallax по указателю сдвигает слои на РАЗНОЕ расстояние (см. `depth`),
 * из-за чего плоская вёрстка читается как сцена.
 */
export type LayerId = "back" | "mid" | "front";

export interface LayerSpec {
  id: LayerId;
  /**
   * Глубина 0…1. Единица — передний план (двигается сильнее всех),
   * ноль — бесконечно далёкий фон (не двигается вовсе).
   * Это же число масштабирует амплитуду parallax из config.PARALLAX.
   */
  depth: number;
  /** Множитель размера растений слоя: дальние мельче. */
  scale: number;
  /** Базовая прозрачность слоя: дальние глуше, это создаёт воздушную перспективу. */
  opacity: number;
  /** Размытие слоя, px — имитация глубины резкости. Передний план всегда 0. */
  blur: number;
  /** Доля растений, попадающих в этот слой. Сумма по всем слоям = 1. */
  share: number;
}

/**
 * Побег по краю подушки — тонкая вайя, торчащая наружу.
 *
 * Раньше растение было РОЗЕТКОЙ из таких вай, расходящихся звездой из центра.
 * От этого пришлось отказаться: широкие остроконечные листья, расходящиеся
 * веером из одной точки, дают силуэт листа конопли. Для компании, продающей
 * мох, это неприемлемое сходство — и оно возникало на каждом кусте.
 *
 * Сфагнум устроен иначе: это плотная подушка из множества мелких побегов, а
 * не звезда. Поэтому теперь основа растения — тело подушки (`body`), а вайи
 * остались только бахромой по её краю.
 */
export interface Frond {
  /** Готовый SVG-path пластинки листа в локальных координатах куста. */
  d: string;
  /** Центральная жилка — рисуется штрихом поверх пластинки. */
  midrib: string;
  /** Угол выхода из центра подушки, °. */
  angle: number;
  /**
   * Насколько далеко от центра НАЧИНАЕТСЯ побег, в локальных единицах.
   *
   * Без этого поля побеги выходили из точки (0,0), то есть из середины
   * подушки, и вместо мохнатого края получалась звёздочка, наштампованная
   * поверх блина. Побег обязан начинаться у КРАЯ и торчать наружу.
   */
  offset: number;
  /** 0…1 — насколько побег «верхний» (влияет на светлоту заливки). */
  depth: number;
}

/**
 * Растение = группа листьев. Именно эта единица появляется со stagger'ом
 * (ТЗ п.3) и живёт собственным ambient-движением (ТЗ п.4).
 */
export interface Plant {
  /** Стабильный ключ для React и для поиска узла в DOM. */
  id: string;
  layer: LayerId;
  /** Позиция центра розетки в % от размеров стены. */
  pos: Vec2;
  /** Итоговый масштаб розетки (уже с учётом множителя слоя). */
  scale: number;
  /** Поворот всей подушки, °. */
  rotate: number;
  /** Листья куста, отсортированы нижними вперёд (нижние уходят под верхние). */
  fronds: Frond[];
  /**
   * Тёплый сдвиг оттенка 0…1. Sphagnum fuscum буквально «бурый» (лат. fuscus —
   * тёмный, бурый): в природе подушки уходят в охру и ржавчину, и сплошная
   * ровная зелень читается искусственным газоном, а не мхом.
   */
  warmth: number;
  /**
   * Порядковый номер в очереди прорастания, 0…1.
   * НЕ индекс в массиве: считается от высоты растения на стене, поэтому
   * нижние кусты появляются первыми и стена растёт снизу вверх.
   */
  growthOrder: number;
  /** Стартовый сдвиг по Y для появления, px (из диапазона LEAVES.yFrom). */
  yFrom: number;
  /** Индивидуальные параметры бесконечного движения — у каждого растения свои. */
  ambient: AmbientParams;
  /** Оттенок зелени 0…1 (0 — глубокий мох, 1 — светлый лайм). */
  tone: number;
  /**
   * Порог плотности: 0 — растение видно везде, включая телефон; 1 — от планшета;
   * 2 — только десктоп. Прячется через CSS по `data-tier`, а не отсечением при
   * генерации: статика собирается одна на все устройства, и решать «сколько
   * узлов рисовать» по ширине окна пришлось бы уже после гидрации.
   */
  tier: 0 | 1 | 2;
}

/**
 * Параметры ambient-движения одного растения.
 * Четыре независимых колебания с разными периодами и фазами — см. config.AMBIENT.
 */
export interface AmbientParams {
  sway: Oscillation;
  breathe: Oscillation;
  driftX: Oscillation;
  driftY: Oscillation;
}

export interface Oscillation {
  /** Амплитуда (°, px или доля масштаба — зависит от свойства). */
  amount: number;
  /** Полупериод колебания, с. */
  duration: number;
  /** Стартовый сдвиг фазы, с. Именно он расстраивает растения между собой. */
  phase: number;
}

/** Готовая раскладка стены — результат работы leaves.ts. */
export interface WallLayout {
  layers: LayerSpec[];
  plants: Plant[];
  /** Блики света: позиция в %, радиус в %, параметры дрейфа. */
  glints: Glint[];
}

export interface Glint {
  id: string;
  pos: Vec2;
  /** Радиус блика в % от ширины сцены. */
  radius: number;
  /** Параметры очень медленного дрейфа и «дыхания» яркости. */
  drift: Oscillation;
  glow: Oscillation;
  /** Тёплый (солнце) или холодный (небо) блик. */
  warm: boolean;
}

/**
 * Что init() возвращает наружу.
 *
 * `destroy` обязателен: без него ScrollTrigger'ы переживают размонтирование
 * компонента, продолжают считать позиции удалённых узлов и текут по памяти.
 * `refresh` нужен при СМЕНЕ КОНТЕНТА (ТЗ: «поддержка повторной инициализации»):
 * высоты пересчитываются, привязки остаются.
 */
export interface CoverMotionHandle {
  destroy: () => void;
  refresh: () => void;
}
