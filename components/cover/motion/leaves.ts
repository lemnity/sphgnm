/**
 * Раскидывает точки по площади стены.
 *
 * Не чистый rand по площади: он сбивается в комки и оставляет проплешины
 * (это известное свойство равномерного распределения — «случайное» на глаз
 * выглядит кучным). Вместо этого — джиттерная сетка: площадь режется на ячейки,
 * в каждой ставится одна точка со случайным смещением внутри ячейки. Плотность
 * получается ровной, а регулярность сетки джиттером уже не читается.
 *
 * `bottomBias` прижимает точки к низу: настоящая стена внизу гуще — там больше
 * влаги и там она нарастает первой.
 */
function scatter(rng: Rng, count: number, bottomBias: number): { x: number; y: number }[] {
  const pts: { x: number; y: number }[] = [];
  // Пропорции ячейки подбираем так, чтобы сетка была примерно квадратной
  // при вертикальном формате стены.
  const cols = Math.max(2, Math.round(Math.sqrt(count * 0.62)));
  const rows = Math.max(2, Math.ceil(count / cols));

  for (let i = 0; i < count; i++) {
    const col = i % cols;
    const row = Math.floor(i / cols);
    // 0.5 в центр ячейки + джиттер ±0.5 ячейки.
    const cx = ((col + 0.5 + range(rng, -0.46, 0.46)) / cols) * 100;
    const cy = ((row + 0.5 + range(rng, -0.46, 0.46)) / rows) * 100;

    // Смещение к низу: возведение нормированной высоты в степень < 1 тянет
    // распределение вниз, не обрезая верх.
    const biased = 100 * Math.pow(cy / 100, 1 - bottomBias);

    pts.push({ x: round(cx, 2), y: round(biased, 2) });
  }
  return pts;
}

/**
 * Детерминированная тасовка (Фишер—Йетс на нашем rng).
 *
 * Нужна для распределения растений по «тирам» плотности: на телефоне рисуется
 * только часть стены, и эта часть обязана быть РАВНОМЕРНО разбросанной. Если
 * просто взять первые N из сетки, на мобильном останется левый верхний угол.
 */
function shuffle<T>(rng: Rng, items: T[]): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j] as T, out[i] as T];
  }
  return out;
}

/**
 * Собирает полное описание стены.
 *
 * Растений всегда генерируется максимум (LEAVES.count.desktop), а лишние на
 * узких экранах прячутся через CSS по атрибуту `data-tier`. Так сделано
 * намеренно: статика собирается ОДНА на все устройства, и генерировать разное
 * количество узлов «по ширине окна» пришлось бы уже в браузере — то есть после
 * гидрации, с перестройкой всего поддерева и мерцанием стены на первом кадре.
 */
export function buildWall(seed: number = WALL_SEED): WallLayout {
  const plants: Plant[] = [];

  LAYERS.forEach((layer, layerIndex) => {
    // Свой поток на каждый слой: добавление растения в один слой не должно
    // перетасовывать два других.
    const rng = createRng(seed + layerIndex * 7919);
    const count = Math.round(LEAVES.count.desktop * layer.share);

    // Дальний план разбросан ровнее, передний — заметно прижат к низу:
    // так стена «стоит на земле», а не висит в воздухе.
    const bottomBias = layer.id === "front" ? 0.42 : layer.id === "mid" ? 0.26 : 0.12;
    const points = scatter(rng, count, bottomBias);

    // Тир назначаем ПОСЛЕ тасовки, поэтому мобильная выборка остаётся
    // равномерно разбросанной по всей площади слоя.
    const order = shuffle(rng, points.map((_, i) => i));
    const phoneQuota = Math.max(1, Math.round(LEAVES.count.phone * layer.share));
    const tabletQuota = Math.max(2, Math.round(LEAVES.count.tablet * layer.share));

    const tierOf = (rank: number): 0 | 1 | 2 =>
      rank < phoneQuota ? 0 : rank < tabletQuota ? 1 : 2;

    points.forEach((pos, i) => {
      const rank = order.indexOf(i);

      // Бахромы больше у переднего плана: у дальних подушек волоски всё равно
      // не читаются, а узлов стоят столько же. Числа снижены после того, как
      // количество подушек выросло с 48 до 130 — бюджет узлов держим примерно
      // постоянным (~1100 путей на стену).
      // Листьев в кусте. Больше десяти — они сливаются в шар и перестают
      // читаться по отдельности; меньше пяти — куст выглядит ощипанным.
      const leafCount =
        layer.id === "front" ? intRange(rng, 7, 11) : layer.id === "mid" ? intRange(rng, 6, 9) : intRange(rng, 4, 7);
      // Радиус в локальных координатах куста (viewBox −100…100).
      const radius = bell(rng, 62, 88);

      plants.push({
        id: `${layer.id}-${i}`,
        layer: layer.id,
        pos,
        // bell, а не range: большинство подушек среднего размера, крайности редки.
        scale: round(bell(rng, 0.72, 1.28) * layer.scale, 3),
        rotate: round(range(rng, -16, 16), 1),
        fronds: buildLeaves(rng, leafCount, radius),
        // Треть подушек уходит в охру. Держим долю небольшой: сплошь бурая
        // стена выглядит засохшей, а ровно зелёная — искусственным газоном.
        warmth: round(rng() < 0.34 ? range(rng, 0.25, 0.7) : range(rng, 0, 0.14), 3),
        // Очередь прорастания считается от ВЫСОТЫ: нижние растения появляются
        // первыми, и стена растёт снизу вверх (ТЗ п.2–3). Джиттер не даёт
        // кромке идти идеальной горизонтальной линией — это выглядело бы
        // как заливка прогресс-бара, а не как рост.
        growthOrder: round(clamp01(1 - pos.y / 100 + range(rng, -0.09, 0.09)), 3),
        yFrom: round(rangeOf(rng, LEAVES.yFrom), 1),
        ambient: buildAmbient(rng),
        // Передний план светлее заднего — это и есть воздушная перспектива.
        tone: round(clamp01(range(rng, 0.18, 0.82) + layer.depth * 0.22), 3),
        tier: tierOf(rank),
      });
    });
  });

  // Рисуем от дальнего к переднему. В SVG нет z-index — порядок в документе
  // и есть порядок наложения.
  plants.sort((a, b) => layerRank(a.layer) - layerRank(b.layer));

  return { layers: LAYERS, plants, glints: buildGlints(seed) };
}

function layerRank(id: Plant["layer"]): number {
  return LAYERS.findIndex((l) => l.id === id);
}

function clamp01(v: number): number {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

/* ───────────────────────────────────────────────────────────────────────────
 *  СОЛНЕЧНЫЕ БЛИКИ (ТЗ п.8)
 *
 *  Четыре мягких радиальных пятна, которые очень медленно ездят и дышат
 *  яркостью. Никакого WebGL: пятно — это один div с radial-gradient, а вся
 *  «жизнь» в нём — transform и opacity, то есть работа композитора, а не
 *  пересчёт пикселей.
 * ─────────────────────────────────────────────────────────────────────────── */
function buildGlints(seed: number): Glint[] {
  const rng = createRng(seed + 104729);
  const glints: Glint[] = [];

  // Три тёплых (солнце сквозь листву) и один холодный (отражённое небо).
  // Холодный нужен для контраста температуры: сцена из одних тёплых пятен
  // выглядит подкрашенной, а не освещённой.
  const specs: { pos: [number, number]; radius: number; warm: boolean }[] = [
    { pos: [22, 18], radius: 46, warm: true },
    { pos: [68, 42], radius: 38, warm: true },
    { pos: [38, 74], radius: 52, warm: false },
    { pos: [82, 12], radius: 30, warm: true },
  ];

  specs.forEach((spec, i) => {
    glints.push({
      id: `glint-${i}`,
      pos: { x: spec.pos[0], y: spec.pos[1] },
      radius: spec.radius,
      drift: oscillation(rng, LIGHT.driftAmount, LIGHT.driftDuration),
      glow: oscillation(rng, LIGHT.glowOpacity, LIGHT.glowDuration),
      warm: spec.warm,
    });
  });

  return glints;
}
