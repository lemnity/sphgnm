  // накрывает 16 розеток, и каждый пиксель радиуса — это работа на весь слой.
  // На 1.6 px глубина резкости читается ровно так же (дальние кусты и без того
  // мельче и подмешаны к цвету фона), а кадр дешевле.
  //
  // opacity здесь БОЛЬШЕ НЕ ПРИМЕНЯЕТСЯ как CSS-свойство: оно впечатывается в
  // цвет листьев на сборке (см. leafFill). Поле осталось именно как параметр
  // воздушной перспективы — просто потребитель у него теперь другой.
  // ВАЖНО: размытие осталось ТОЛЬКО на дальнем плане — единственном слое, чьё
