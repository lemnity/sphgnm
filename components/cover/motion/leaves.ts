/**
 * ЛИСТ — широкая овальная пластинка на черешке.
 *
 * ═══ ДВЕ ПРЕДЫДУЩИЕ ПОПЫТКИ И ЧЕМУ ОНИ НАУЧИЛИ ═══
 *
 * 1. РОЗЕТКА ИЗ УЗКИХ ОСТРОКОНЕЧНЫХ ЛИСТЬЕВ. Дала силуэт конопли на каждом
 *    кусте — для компании, продающей мох, недопустимо.
 * 2. АБСТРАКТНЫЕ ПОДУШКИ-ПЯТНА. От конопли ушли, но растения перестали быть
 *    растениями: получились цветные кляксы.
 *
 * Вывод: дело не в расположении листьев, а в ПРОПОРЦИИ пластинки. У конопли
 * листочки узкие — ширина около 15% длины; спутать широкий лист с ней
 * невозможно, как бы они ни росли. Поэтому здесь ширина 48–68% длины, край
 * гладкий (никаких зубцов — второй опознавательный признак конопли), кончик
 * скруглённый. Такой лист однозначно читается как филодендрон или пеперомия —
 * то, из чего фитостены и собирают.
 *
 * Путь строится из четырёх кубических кривых: черешок → расширение →
 * кончик → обратно. Пластинка асимметрична (нижняя кромка полнее верхней) —
 * идеально симметричный лист выглядит вырезанным по трафарету.
 */
function leafPath(len: number, width: number, curve: number): string {
  const r = (n: number) => round(n, 1);
  const w = width / 2;
  // Черешок — первые 16% длины. Именно он превращает «пластинку» в лист,
  // растущий откуда-то, а не в плавающий овал.
  const st = len * 0.16;
  // Точка максимальной ширины — в первой трети: так лист выглядит растущим
  // от основания, а не веретеном.
  const bx = st + (len - st) * 0.26;

  return (
    `M0 0` +
    // Верхняя кромка: от основания черешка к самому широкому месту.
    `C${r(st * 0.5)} ${r(-w * 0.1)} ${r(st * 0.92)} ${r(-w * 0.62)} ${r(bx)} ${r(-w)}` +
    // Дальше к кончику. curve уводит остриё в сторону — лист изгибается.
    `C${r(len * 0.68)} ${r(-w * 0.92 + curve * 0.4)} ${r(len * 0.93)} ${r(-w * 0.36 + curve * 0.8)} ${r(len)} ${r(curve)}` +
    // Обратно по нижней кромке. Множители чуть больше верхних — асимметрия.
    `C${r(len * 0.92)} ${r(w * 0.42 + curve * 0.8)} ${r(len * 0.66)} ${r(w * 0.98 + curve * 0.4)} ${r(bx)} ${r(w)}` +
    `C${r(st * 0.9)} ${r(w * 0.66)} ${r(st * 0.48)} ${r(w * 0.12)} 0 0Z`
  );
}

/** Центральная жилка — тонкая дуга от основания к кончику. */
function midribPath(len: number, curve: number): string {
  const r = (n: number) => round(n, 1);
  return `M${r(len * 0.12)} 0Q${r(len * 0.6)} ${r(curve * 0.35)} ${r(len * 0.9)} ${r(curve * 0.86)}`;
}

/**
 * Куст — пучок листьев, расходящихся вверх из общего основания.
 *
 * Веер направлен ВВЕРХ (−210°…30°), а не по кругу: растение на стене тянется
 * к свету, а полный круг вернул бы ту самую звезду. Нижние листья короче и
 * темнее, верхние длиннее и светлее — так куст читается объёмным.
 */
function buildLeaves(rng: Rng, count: number, radius: number): Frond[] {
  const out: Frond[] = [];

  for (let i = 0; i < count; i++) {
    // Веер с заходом за горизонталь: пара листьев обязана свисать вбок,
    // иначе куст выглядит зажатым в кулак.
    const angle = range(rng, -212, 32);
    // 1 для строго вертикального листа, 0 для смотрящего вниз.
    const upness = (Math.cos((angle + 90) * DEG) + 1) / 2;

    const len = bell(rng, radius * 0.5, radius) * (0.72 + 0.42 * upness);
    // ШИРИНА 48–68% ДЛИНЫ. Это главное число всего файла: именно оно
    // отличает лист фитостены от листочка конопли (у той ~15%).
    const width = len * range(rng, 0.48, 0.68);
    const curve = sign(rng) * len * range(rng, 0.05, 0.22);
    // Лист выходит не из математического центра, а чуть в стороне —
    // основания разнесены, и куст не сходится в одну точку.
    const offset = radius * range(rng, 0.02, 0.16);

    out.push({
      d: leafPath(round(len, 1), round(width, 1), round(curve, 1)),
      midrib: midribPath(round(len, 1), round(curve, 1)),
      angle: round(angle, 1),
      offset: round(offset, 1),
      depth: round(upness, 2),
    });
  }

  // Нижние листья рисуются первыми и уходят под верхние.
  return out.sort((a, b) => a.depth - b.depth);
}

/* ───────────────────────────────────────────────────────────────────────────
 *  AMBIENT-ПАРАМЕТРЫ
 * ─────────────────────────────────────────────────────────────────────────── */

/** Одно независимое колебание: амплитуда, период и — главное — фаза. */
function oscillation(rng: Rng, amount: readonly [number, number], duration: readonly [number, number]): Oscillation {
  return {
    amount: round(rangeOf(rng, amount), 3),
    duration: round(rangeOf(rng, duration), 2),
    // Фаза — то, что расстраивает растения между собой. Без неё вся стена
    // качается в такт и мгновенно читается CSS-анимацией по классу.
    phase: round(rng() * AMBIENT.phaseSpread, 2),
  };
}

function buildAmbient(rng: Rng): AmbientParams {
  return {
    sway: oscillation(rng, AMBIENT.sway.amount, AMBIENT.sway.duration),
    breathe: oscillation(rng, AMBIENT.breathe.amount, AMBIENT.breathe.duration),
    driftX: oscillation(rng, AMBIENT.driftX.amount, AMBIENT.driftX.duration),
    driftY: oscillation(rng, AMBIENT.driftY.amount, AMBIENT.driftY.duration),
  };
}

